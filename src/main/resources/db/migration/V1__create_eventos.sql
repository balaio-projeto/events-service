CREATE TABLE eventos
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    slug              VARCHAR(255) NOT NULL UNIQUE,
    nome              VARCHAR(255) NOT NULL,
    tipo              VARCHAR(130) NOT NULL,
    organizador       VARCHAR(255) NOT NULL,
    descricao         TEXT         NOT NULL,
    status_aprovacao  VARCHAR(50)  NOT NULL DEFAULT 'PENDENTE',
    status_publicacao VARCHAR(50)  NOT NULL DEFAULT 'NAO_PUBLICADO',
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    horario_inicio TIME,
    horario_fim TIME,
    entrada VARCHAR(255),
    cidade VARCHAR(150) NOT NULL,
    local VARCHAR(255) NOT NULL,
    endereco VARCHAR(500) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,

    CONSTRAINT id_primaryKey PRIMARY KEY (id),
    CONSTRAINT chk_status_aprovacao
    CHECK (status_aprovacao IN ('PENDENTE', 'APROVADO', 'REJEITADO')),
    CONSTRAINT chk_status_publicacao
    CHECK (status_publicacao IN ('NAO_PUBLICADO', 'PUBLICADO')),

    CONSTRAINT chk_periodo_evento
        CHECK (data_fim >= data_inicio),

    CONSTRAINT chk_eventos_latitude
        CHECK (
            latitude IS NOT NULL
                AND latitude <> 'NaN'::double precision
            AND latitude BETWEEN -90 AND 90
    ),

    CONSTRAINT chk_eventos_longitude
        CHECK (
            longitude IS NOT NULL
            AND longitude <> 'NaN'::double precision
            AND longitude BETWEEN -180 AND 180
        )
);